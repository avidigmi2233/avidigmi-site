export const getPost = (slug: string) => {
  const decoded = decodeURIComponent(slug);
  return posts.find((p) => p.slug === decoded);
};

/** fetch the article HTML for a post (already sanitised at build time) */
export async function loadPostBody(post: Post): Promise<string> {
  const res = await fetch(`/content/posts/${post.file}.json`);
  if (!res.ok) throw new Error(`post body not found: ${post.file}`);
  const data = (await res.json()) as { body: string };
  return data.body;
}

